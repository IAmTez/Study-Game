/*
 * Bundles the game into one self-contained HTML file.
 *
 * The playable source is a set of ES modules served over HTTP. This walks the
 * module graph from js/main.js, rewrites the static import/export statements
 * into a tiny CommonJS-style registry, and inlines everything — CSS included —
 * into a single page that opens straight from the file system and can be
 * published as a standalone artifact.
 *
 *   node tools/bundle.mjs [outfile]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = 'js/main.js';
const OUT = process.argv[2] || path.join(ROOT, 'dist', 'sewers-of-study.html');

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

/* ---------------------------------------------------------------
   Module graph
   --------------------------------------------------------------- */

const modules = new Map();   // id -> { id, source, deps }

/** Static imports only — a dynamic import() is left alone for the runtime. */
const STATIC_IMPORT = /^[ \t]*import\s*(?:\{([\s\S]*?)\}|\*\s*as\s+([A-Za-z0-9_$]+))\s*from\s*['"]([^'"]+)['"];?[ \t]*$/gm;

function collect(id) {
  if (modules.has(id)) return;
  const abs = path.join(ROOT, id);
  const source = fs.readFileSync(abs, 'utf8');
  const deps = [];
  for (const match of source.matchAll(STATIC_IMPORT)) {
    deps.push(rel(path.resolve(path.dirname(abs), match[3])));
  }
  modules.set(id, { id, source, deps });
  for (const dep of deps) collect(dep);
}

/** Depth-first order, so every module is defined before anything requires it. */
function orderModules(entry) {
  const order = [];
  const state = new Map();   // id -> 'visiting' | 'done'
  const cycles = [];

  (function visit(id, stack) {
    if (state.get(id) === 'done') return;
    if (state.get(id) === 'visiting') {
      cycles.push([...stack.slice(stack.indexOf(id)), id].join(' -> '));
      return;
    }
    state.set(id, 'visiting');
    for (const dep of modules.get(id).deps) visit(dep, [...stack, id]);
    state.set(id, 'done');
    order.push(id);
  })(entry, []);

  if (cycles.length) {
    // The registry evaluates eagerly, so a cycle would hand back a half-built
    // module. Fail loudly rather than shipping something subtly broken.
    throw new Error(`Circular imports found:\n  ${cycles.join('\n  ')}`);
  }
  return order;
}

/* ---------------------------------------------------------------
   Source rewriting
   --------------------------------------------------------------- */

function transform(module) {
  const dir = path.dirname(path.join(ROOT, module.id));
  const exported = new Set();
  let out = module.source;

  out = out.replace(STATIC_IMPORT, (_all, named, namespace, spec) => {
    const target = rel(path.resolve(dir, spec));
    if (namespace) return `const ${namespace} = __require(${JSON.stringify(target)});`;
    // `a, b as c` -> `a, b: c`
    const bindings = named
      .split(',')
      .map(s => s.trim())
      .filter(Boolean)
      .map(s => {
        const [name, alias] = s.split(/\s+as\s+/).map(t => t.trim());
        return alias ? `${name}: ${alias}` : name;
      })
      .join(', ');
    return `const { ${bindings} } = __require(${JSON.stringify(target)});`;
  });

  // `export function f` / `export async function f` / `export const X`
  out = out.replace(/^[ \t]*export\s+(async\s+function|function|const|let|class)\s+([A-Za-z0-9_$]+)/gm,
    (_all, kind, name) => { exported.add(name); return `${kind} ${name}`; });

  if (/^\s*export\s/m.test(out)) {
    const leftover = out.match(/^\s*export\s.*$/m)[0].trim();
    throw new Error(`${module.id}: unhandled export form -> ${leftover}`);
  }

  const assignments = [...exported].map(n => `  __exports.${n} = ${n};`).join('\n');
  return { code: out, assignments, exported };
}

/* ---------------------------------------------------------------
   Build
   --------------------------------------------------------------- */

collect(ENTRY);
const order = orderModules(ENTRY);

const bodies = order.map(id => {
  const { code, assignments } = transform(modules.get(id));
  return `__define(${JSON.stringify(id)}, function (__exports, __require) {\n${code}\n${assignments}\n});`;
}).join('\n\n');

const runtime = `
/* --- module registry (generated by tools/bundle.mjs) --- */
var __defs = {}, __cache = {};
function __define(id, fn) { __defs[id] = fn; }
function __require(id) {
  if (__cache[id]) return __cache[id];
  var exports = __cache[id] = {};
  var fn = __defs[id];
  if (!fn) throw new Error('module not bundled: ' + id);
  fn(exports, __require);
  return exports;
}
`;

const css = fs.readFileSync(path.join(ROOT, 'css/main.css'), 'utf8');
const indexHtml = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const bodyMatch = indexHtml.match(/<body>([\s\S]*?)<script type="module"/);
if (!bodyMatch) throw new Error('could not read the markup out of index.html');
const markup = bodyMatch[1].trim();
const fontLink = (indexHtml.match(/<link href="https:\/\/fonts\.googleapis\.com[^>]*>/) || [''])[0];

const page = `<title>Sewers of Study</title>
${fontLink}
<style>
${css}
</style>

${markup}

<script>
(function () {
'use strict';
${runtime}
${bodies}

__require(${JSON.stringify(ENTRY)});
})();
</script>
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, page);

const kb = (Buffer.byteLength(page) / 1024).toFixed(0);
console.log(`bundled ${order.length} modules -> ${rel(OUT)} (${kb} KB)`);
